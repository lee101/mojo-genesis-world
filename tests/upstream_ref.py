"""Run the vendored `genesis-world` sources as ordinary Python.

The vendored files are upstream's, unmodified. Quadrants has a `python` backend
in which a `@qd.func` is an ordinary Python function over NumPy-backed
`qd.Vector` / `qd.Matrix` values, so `qd.static` unrolling, `qd.select`,
`qd.Matrix.identity` and `@`-matrix-multiply all behave exactly as the engine
compiles them, with no rewriting of the source at all. What this module supplies
is the engine around them: a stub `genesis` package whose `qd_float` and `qd_vec3`
are what `genesis/__init__.py` sets for a 64-bit CPU run, and look-alike
`array_class` objects the tests fill in as a kernel's "engine state".

See `tests/upstream/LICENSE-NOTICE.md`.
"""

from __future__ import annotations

import sys
import types

import numpy as np
import quadrants as qd
import quadrants.lang as ql

# quadrants' Python backend builds its tensors at torch's default dtype, which is
# float32; the engine runs a 64-bit build, so ask torch for float64 first.
import torch as _torch  # noqa: E402

_torch.set_default_dtype(_torch.float64)
ql.init(arch=qd.python, default_fp=qd.f64)

# quadrants 1.3.0's Python backend implements `Vector.x` as `super()[0]`, which
# is a no-argument `super()` and cannot be subscripted. Upstream's geom.py uses
# `.x` / `.y` / `.z`; on a GPU backend those accessors are generated by the
# compiler and work. Restore the obvious meaning.
from quadrants.lang._py_tensor import PyTensor as _PyTensor  # noqa: E402

# `Vector.norm(eps)` is also wrong in the Python backend: it returns inf for any
# nonzero eps, where the compiled backends compute quadrants' own definition,
# `sqrt(norm_sqr + eps)` (quadrants/lang/matrix_ops.py:269). Restore that.
_PyTensor.norm = lambda self, eps=0: _torch.sqrt(self.norm_sqr() + eps)
_PyTensor.x = property(lambda self: _torch.Tensor.__getitem__(self, 0))
_PyTensor.y = property(lambda self: _torch.Tensor.__getitem__(self, 1))
_PyTensor.z = property(lambda self: _torch.Tensor.__getitem__(self, 2))

HERE = __file__.rsplit("/", 1)[0]
ROOT = f"{HERE}/upstream"

qd_float = qd.f64
qd_int = qd.i32

FLOAT_MAX = float(np.finfo(np.float32).max)
FLOAT_MIN = 1e-15
FLOAT_MIN_SQ = 1e-30
EPS = 1e-15


class Scalar(float):
    """A float that answers `[None]`, the way upstream reads a zero-extent field."""

    def __getitem__(self, key):
        return self


class Vec3Field:
    """An `array_class` field of vec3 values: indexing one yields a `qd.Vector`.

    `geoms_init_AABB` is a `qd.Tensor` of shape `(n_geoms, 8)` whose elements are
    vec3, so upstream's `geoms_init_AABB[i_g, 7] - geoms_init_AABB[i_g, 0]` is
    vec3 arithmetic with a `.norm()` on the result.
    """

    def __init__(self, a):
        self.a = a.a if isinstance(a, Vec3Field) else np.asarray(a, dtype=np.float64)

    def __getitem__(self, idx):
        return V3(self.a[idx])


class Fields:
    """Stand-in for an `array_class` dataclass: attribute access over a dict."""

    def __init__(self, **kw):
        self.__dict__.update(kw)

    def __repr__(self):
        return f"Fields({self.__dict__})"

    def __getitem__(self, key):
        # Upstream reads scalar engine fields as `field[None]` (a zero-extent
        # tensor). A stand-in has nothing to index into, so the only key that
        # makes sense is that one.
        if key is None or key == ():
            return self
        raise KeyError(key)


def V3(a) -> "qd.Vector":
    """A `qd.Vector` of length 3, as the engine's kernels receive it."""
    a = np.asarray(a, dtype=np.float64).reshape(3)
    return qd.Vector([float(a[0]), float(a[1]), float(a[2])], dt=qd_float)


def V4(a) -> "qd.Vector":
    a = np.asarray(a, dtype=np.float64).reshape(4)
    return qd.Vector([float(a[0]), float(a[1]), float(a[2]), float(a[3])], dt=qd_float)


def M3(a) -> "qd.Matrix":
    """A `qd.Matrix` 3x3 built from a `(3, 3)` array."""
    a = np.asarray(a, dtype=np.float64).reshape(3, 3)
    return qd.Matrix([[float(r[0]), float(r[1]), float(r[2])] for r in a], dt=qd_float)


def to_v3(x) -> np.ndarray:
    return np.array([x[0], x[1], x[2]], dtype=np.float64)


def to_v4(x) -> np.ndarray:
    return np.array([x[0], x[1], x[2], x[3]], dtype=np.float64)


def to_m3(x) -> np.ndarray:
    # A quadrants `@` between 3x3 matrices carries a leading unit axis in the
    # Python backend; a Matrix read by index does not. Accept either.
    a = np.asarray(x)
    if a.ndim == 3:
        return a.reshape(-1, 3, 3)[0].astype(np.float64)
    return np.array([[x[i, j] for j in range(3)] for i in range(3)], dtype=np.float64)


def V3s(a) -> list:
    """A batch of `V3`, one per row of an `(n, 3)` array."""
    a = np.asarray(a, dtype=np.float64).reshape(-1, 3)
    return [V3(r) for r in a]


def V4s(a) -> list:
    a = np.asarray(a, dtype=np.float64).reshape(-1, 4)
    return [V4(r) for r in a]


def M3s(a) -> list:
    a = np.asarray(a, dtype=np.float64).reshape(-1, 3, 3)
    return [M3(m) for m in a]


# --------------------------------------------------------------------- stub engine


def _stub_package(name: str) -> types.ModuleType:
    mod = types.ModuleType(name)
    mod.__path__ = []
    sys.modules[name] = mod
    parent, _, leaf = name.rpartition(".")
    if parent:
        setattr(sys.modules[parent], leaf, mod)
    return mod


def _make_gs() -> types.ModuleType:
    gs = types.ModuleType("genesis")
    gs.__path__ = []
    gs.qd_float = qd_float
    gs.qd_int = qd_int
    gs.EPS = EPS
    gs.np_float = np.float64
    gs.np_int = np.int32
    def qd_vec3(x=0.0, y=0.0, z=0.0):
        return qd.Vector([float(x), float(y), float(z)], dt=qd_float)

    gs.qd_vec3 = qd_vec3
    gs.raise_exception = lambda *a: (_ for _ in ()).throw(RuntimeError(a))
    gs.GEOM_TYPE = types.SimpleNamespace(
        PLANE=0, SPHERE=1, ELLIPSOID=2, CYLINDER=3, CAPSULE=4, BOX=5, MESH=6, TERRAIN=7,
        PARA_LEVEL=types.SimpleNamespace(PARTIAL=1),
    )
    for name in ("PLANE", "SPHERE", "ELLIPSOID", "CYLINDER", "CAPSULE", "BOX", "MESH", "TERRAIN"):
        setattr(gs, name, getattr(gs.GEOM_TYPE, name))
    return gs


def _install_stubs() -> None:
    gs = _make_gs()
    sys.modules["genesis"] = gs
    for pkg in (
        "genesis.utils",
        "genesis.engine",
        "genesis.engine.solvers",
        "genesis.engine.solvers.rigid",
        "genesis.engine.solvers.rigid.collider",
        "genesis.materials",
    ):
        _stub_package(pkg)
    for name in (
        "genesis.utils.array_class",
        "genesis.utils.deprecated_module_wrapper",
        "genesis.typing",
    ):
        _stub_package(name)
    ac = sys.modules["genesis.utils.array_class"]
    # Kernel signatures are annotated with real quadrants structs in the engine;
    # an empty struct is a valid stand-in for the annotation check.
    ac.__getattr__ = lambda name: qd.types.struct()
    sys.modules["genesis.utils.deprecated_module_wrapper"].create_virtual_deprecated_module = (
        lambda *a, **k: None
    )
    sys.modules["genesis.typing"].Vec3FType = object
    gs.utils = sys.modules["genesis.utils"]
    sys.modules["genesis.utils"].array_class = ac


_loaded: dict[str, types.ModuleType] = {}


def _load(name: str, path: str) -> types.ModuleType:
    if name in _loaded:
        return _loaded[name]
    ns: dict = {"__name__": name, "__file__": f"{ROOT}/{path}"}
    exec(compile(open(f"{ROOT}/{path}").read(), f"{ROOT}/{path}", "exec"), ns)
    mod = types.ModuleType(name)
    mod.__dict__.update(ns)
    sys.modules[name] = mod
    parent, _, leaf = name.rpartition(".")
    if parent and parent in sys.modules:
        setattr(sys.modules[parent], leaf, mod)
    _loaded[name] = mod
    return mod


def _load_collider_utils() -> types.ModuleType:
    """`collider/utils.py` imports the engine; only its pure helpers are needed."""
    name = "genesis.engine.solvers.rigid.collider.utils"
    src = open(f"{ROOT}/genesis/engine/solvers/rigid/collider/utils.py").read()
    import re

    src = re.sub(r"^from .*import .*$", "", src, flags=re.M)
    src = re.sub(r"^import .*$", "", src, flags=re.M)
    ns: dict = {
        "__name__": name,
        "__file__": f"{ROOT}/genesis/engine/solvers/rigid/collider/utils.py",
        "qd": qd,
        "gs": sys.modules["genesis"],
        "np": np,
        "math": sys.modules.get("math") or __import__("math"),
        "array_class": sys.modules["genesis.utils.array_class"],
    }
    exec(compile(src, "utils.py", "exec"), ns)
    mod = types.ModuleType(name)
    mod.__dict__.update(ns)
    sys.modules[name] = mod
    setattr(sys.modules["genesis.engine.solvers.rigid.collider"], "utils", mod)
    return mod


def load() -> dict:
    """Import every vendored module and return a namespace of them."""
    if "_all" in _loaded:
        return _loaded["_all"]
    _install_stubs()
    gs = sys.modules["genesis"]

    constants = _load(
        "genesis.engine.solvers.rigid.collider.constants",
        "genesis/engine/solvers/rigid/collider/constants.py",
    )
    utils = _load_collider_utils()
    geom = _load("genesis.utils.geom", "genesis/utils/geom.py")
    sys.modules["genesis.utils"].geom = geom
    simt = _load("genesis.utils.simt", "genesis/utils/simt.py")
    sup = _load(
        "genesis.engine.solvers.rigid.collider.support_field",
        "genesis/engine/solvers/rigid/collider/support_field.py",
    )
    gjk_s = _load(
        "genesis.engine.solvers.rigid.collider.gjk_support",
        "genesis/engine/solvers/rigid/collider/gjk_support.py",
    )
    gjk_u = _load(
        "genesis.engine.solvers.rigid.collider.gjk_utils",
        "genesis/engine/solvers/rigid/collider/gjk_utils.py",
    )
    contact = _load(
        "genesis.engine.solvers.rigid.collider.contact",
        "genesis/engine/solvers/rigid/collider/contact.py",
    )
    tail = _load("mpm_solver_tail", "mpm_solver_tail.py")
    activate_src = _load("support_field_activate", "support_field_activate.py")

    ns = {
        "geom": geom,
        "simt": simt,
        "support_field": sup,
        "gjk_support": gjk_s,
        "gjk_utils": gjk_u,
        "contact": contact,
        "tail": tail,
        "activate_src": activate_src,
        "constants": constants,
        "utils": utils,
        "Fields": Fields,
        "gs": gs,
    }
    for mod in ("base", "elastic", "elasto_plastic", "liquid", "sand", "snow"):
        ns[f"mpm_{mod}"] = _load(f"mpm_materials.{mod}", f"mpm_materials/{mod}.py")
    _loaded["_all"] = ns
    return ns


# ------------------------------------------------------------- engine-state makers


def collider_info(support_res: int = 180, support_v=None, support_vid=None,
                  support_cell_start=None, mc_tolerance: float = 1e-3) -> Fields:
    return Fields(
        gjk=Fields(FLOAT_MAX=Scalar(FLOAT_MAX), FLOAT_MIN=Scalar(FLOAT_MIN), FLOAT_MIN_SQ=Scalar(FLOAT_MIN_SQ)),
        support_field=Fields(
            support_res=Scalar(support_res),
            support_v=None if support_v is None else Vec3Field(support_v),
            support_vid=support_vid,
            support_cell_start=support_cell_start,
        ),
        mc_tolerance=Scalar(mc_tolerance),
    )


def gjk_state(n: int) -> Fields:
    return Fields(support_mesh_prev_vertex_id=np.zeros(n, dtype=np.int32))


def dyn_info(geom_type, geoms_data, vert_start, vert_end, init_pos) -> Fields:
    return Fields(
        geoms=Fields(type=np.asarray(geom_type, dtype=np.int32),
                     data=np.asarray(geoms_data, dtype=np.float64).reshape(-1, 3),
                     vert_start=np.asarray(vert_start, dtype=np.int32),
                     vert_end=np.asarray(vert_end, dtype=np.int32)),
        verts=Fields(init_pos=Vec3Field(init_pos)),
    )
